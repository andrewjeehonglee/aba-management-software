-- =============================================================================
-- Patch: Reinterpret demo session times as Pacific wall clock
-- =============================================================================
-- Seed stored "08:00", "13:00" etc. as UTC (+00:00). In US Pacific that
-- renders as 01:00, 06:00 — looks like early AM instead of clinic hours.
--
-- This keeps the same hour:minute numbers but tags them as America/Los_Angeles,
-- so Today's Sessions shows 08:00, 13:00, 14:00 (24-hour) as intended.
--
-- Run once in Supabase SQL Editor. Safe to re-run (idempotent).
-- =============================================================================

UPDATE sessions
SET scheduled_at = (
  (scheduled_at AT TIME ZONE 'UTC') AT TIME ZONE 'America/Los_Angeles'
)
WHERE id IN (
  '30000000-0000-0000-0000-000000000001',
  '30000000-0000-0000-0000-000000000002',
  '30000000-0000-0000-0000-000000000003',
  '30000000-0000-0000-0000-000000000004',
  '30000000-0000-0000-0000-000000000005',
  '30000000-0000-0000-0000-000000000006',
  '30000000-0000-0000-0000-000000000007',
  '30000000-0000-0000-0000-000000000008',
  '30000000-0000-0000-0000-000000000071',
  '30000000-0000-0000-0000-000000000072',
  '30000000-0000-0000-0000-000000000073',
  '30000000-0000-0000-0000-000000000074',
  '30000000-0000-0000-0000-000000000075',
  '30000000-0000-0000-0000-000000000076'
);
